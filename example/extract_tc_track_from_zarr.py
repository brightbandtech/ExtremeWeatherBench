def prepare_era5_data_for_tc_detection(
    era5_ds: xr.Dataset,
    event_start: np.datetime64 | None = None,
    il_output: bool = False
) -> tuple[xr.DataArray, xr.DataArray, xr.DataArray]:
    """Prepare ERA5 data for TC track detection.
    
    Converts ERA5 variables to the format expected by the TC track detection
    algorithm, including:
    - Renaming variables to match EWB conventions
    - Converting units (Pa to hPa if needed)
    - Ensuring proper coordinate structure
    
    Args:
        era5_ds: Filtered ERA5 dataset from filter_era5_for_tc.py
        
    Returns:
        Tuple of (sea_level_pressure, wind_speed, geopotential_thickness) DataArrays
    """
    # Check required variables
    required_vars = [
        "mean_sea_level_pressure",
        "10m_u_component_of_wind",
        "10m_v_component_of_wind",
        "geopotential_300",
        "geopotential_500",
    ]

    print("  Checking for required variables...")

    missing = [var for var in required_vars if var not in era5_ds.feature.values]
    if missing:
        raise ValueError(
            f"Missing required variables: {missing}. "
            f"Available: {list(era5_ds.fearures.values)}"
        )

    print("  Creating restructured xarray handle...")

    # Start with coordinates and dimensions from original dataset
    modified_ds = xr.Dataset(
        coords={k: v for k, v in era5_ds.coords.items() if k != "feature"}
    )
    
    
    # print(modified_ds.init_time.values)

    
    # Convert feature dimension to data variables
    # This preserves lazy loading by using xarray's indexing without .load() or .compute()
    # print("  Converting 'feature' dimension to data variables...")
    
    # Get the name of the data variable that contains the feature data
    # Typically there's one main data variable indexed by the feature dimension
    data_var_name = list(era5_ds.data_vars)[0]
    
    for feature_name in era5_ds.feature.values:
        # Select data for this feature and assign as a named variable
        # Using .sel() maintains lazy evaluation - data is not loaded until explicitly computed
        # Extract the DataArray from the Dataset result by accessing the underlying variable
        feature_data = era5_ds[data_var_name].sel(feature=feature_name)
        modified_ds[feature_name] = feature_data

    modified_ds = modified_ds.reset_coords("feature", drop=True)
    modified_ds = modified_ds[required_vars]

    print("  Convert lead_time dimension to different notational convention...")

    # print(f"before lead time values: {modified_ds.lead_time.values}")
    

    # Convert lead_time from int32 hours to timedelta64[ns]
    lead_time_hours = modified_ds.coords["lead_time"].values
    # First convert to timedelta64[h] (hours), then to ns
    modified_ds = modified_ds.assign_coords(
        lead_time=lead_time_hours.astype("timedelta64[h]").astype("timedelta64[ns]")
    )

    # print(f"after lead time values: {modified_ds.lead_time.values}")

    if event_start is None:
        earliest_prediction = min(modified_ds.coords["time"].values)
    else:
        earliest_prediction = event_start
        # print(type(event_start), event_start)
        # print(min(modified_ds.coords["time"].values))
        
    # print(earliest_prediction)

    init_time_vals = earliest_prediction - modified_ds.coords["lead_time"].values
    modified_ds = modified_ds.assign_coords(
        lead_time=init_time_vals
    ).rename({"lead_time": "init_time"}) # .isel(init_time=[-1])
    modified_ds = modified_ds.dropna(dim="time", how="all")

    # print(f"init time values: {modified_ds.init_time.values}")

    # Combine geopotential_300 and geopotential_500 into a single geopotential variable with level coordinate
    # This preserves lazy loading by using xr.concat which doesn't trigger computation
    print("  Combining geopotential_300 and geopotential_500 into geopotential with level coordinate...")
    geopotential_levels = xr.concat(
        [modified_ds["geopotential_300"], modified_ds["geopotential_500"]],
        dim="level"
    )
    geopotential_levels = geopotential_levels.assign_coords(level=[300, 500])
    modified_ds["geopotential"] = geopotential_levels
    
    # Remove the individual level-specific variables
    modified_ds = modified_ds.drop_vars(["geopotential_300", "geopotential_500"])
    # print("  Created geopotential variable with level coordinate [300, 500]")
    
    # print(f"  Converted {len(era5_ds.feature.values)} feature to data variables")
    
    # Extract and prepare sea level pressure
    # Ensure it's in Pa (ERA5 typically uses Pa)
    # slp = era5_ds["mean_sea_level_pressure"]
    
    print("  Renaming variables...")

    modified_ds = modified_ds.rename(
        {
            "time": "valid_time",
            "mean_sea_level_pressure": "air_pressure_at_mean_sea_level",
            "10m_u_component_of_wind": "surface_eastward_wind",
            "10m_v_component_of_wind": "surface_northward_wind"
        }
    )

    

    # modified_ds = modified_ds.rename_dims({"time": "init_time"})

    # Calculate wind speed from u and v components
    # u_wind = era5_ds["10m_u_component_of_wind"]
    # v_wind = era5_ds["10m_v_component_of_wind"]
    # wind_speed = calc.calculate_wind_speed(u_wind, v_wind)
    
    # Calculate geopotential thickness (500hPa - 300hPa geopotential difference)
    # ERA5 uses levels, so we need to extract 500hPa and 300hPa
    
    print("  Calculating geopotential thickness...")

    geopotential_thickness = calc.geopotential_thickness(modified_ds["geopotential"], geopotential=True)
    modified_ds["geopotential_thickness"] = geopotential_thickness

    modified_ds = calc.maybe_calculate_wind_speed(modified_ds)

    # valid_time = modified_ds.init_time.values + modified_ds.lead_time.values
    # modified_ds = modified_ds.assign_coords(valid_time=("lead_time", valid_time))
    
    if il_output:
        print("  Converting to init_time coordinates...")
        return utils.convert_init_and_valid_time_to_lead_and_init_time(modified_ds) 
    else:
        print("  Converting to valid_time coordinates...")
        return utils.convert_init_and_valid_time_to_lead_time(modified_ds)


def reformat_track_ds(track_ds, ensemble_member, init_time_index):
    new_ds = utils.convert_valid_time_to_init_time(track_ds)

    # valid_time = new_ds.init_time.values + new_ds.lead_time.values
    # new_ds = new_ds.assign_coords(valid_time=("lead_time", valid_time))

    new_ds = new_ds.reset_coords(["latitude", "longitude"])
    new_ds = new_ds.expand_dims({"ensemble": 1}).assign_coords(ensemble=[ensemble_member])
    new_ds = new_ds.expand_dims({"init_index": 1}).assign_coords(init_index=[init_time_index])

    return new_ds #.to_dataframe()


def get_structured_group_list(zarr_path: str, event_types: list[str] = ["heat_wave", "freeze", "tropical_cyclone"]) -> list[tuple[str, int, int, int]]:
    zarr_handle = zarr.open(zarr_path)
    raw_group_list = list(zarr_handle.group_keys())
    
    
    if not raw_group_list or not any(g.startswith("events_") for g in raw_group_list):
        path_str = str(zarr_path)
        match = re.search(r'events_tropical_cyclone_(\d+)_lt(m?\d+)_off(\d+)', path_str)
        if match:
            case_id = int(match.group(1))
            lead_str = match.group(2)
            offset = int(match.group(3))
            lead_time = -int(lead_str[1:]) if lead_str.startswith('m') else int(lead_str)
            return [("tropical_cyclone", case_id, offset, lead_time)]
        
        match_simple = re.search(r'events_tropical_cyclone_(\d+)', path_str)
        if match_simple:
            return [("tropical_cyclone", int(match_simple.group(1)), 0, 0)]

    filtered_group_list = [entry[7:] for entry in raw_group_list if entry.startswith("events_")]

    pat = re.compile(r'^(?P<id>\d+)_lt(?P<lead>m?\d+)_off(?P<offset>\d+)$')

    structured_group_list = []
    for entry in filtered_group_list:
        for event_type in event_types:
            if entry.startswith(event_type):
                found_type = event_type
                m = pat.fullmatch(entry[len(event_type) + 1:])
                if m:
                    match_dict = m.groupdict()
                    case_id = int(match_dict["id"])
                    offset = int(match_dict["offset"])
                    if "m" in match_dict["lead"]:
                        lead_time = -int(match_dict["lead"][1:])
                    else:
                        lead_time = int(match_dict["lead"])

                    structured_group_list.append((found_type, case_id, offset, lead_time))
                break
            
    return structured_group_list

def get_case_init_time(case_id):
    cases_list = cases.load_ewb_events_yaml_into_case_list()
    for case in cases_list:
        if case.case_id_number == case_id:
            return pd.Timestamp(case.start_date).to_datetime64().astype("datetime64[ns]")

    return None


def extract_tc_track_from_zarr(
    zarr_path: str,
    output_csv_path: str = ".",
    event_types: list[str] = ["tropical_cyclone"],
    **track_detection_kwargs,
) -> pd.DataFrame:
    """Extract tropical cyclone track from filtered ERA5 zarr file.
    
    Uses the TempestExtremes-based TC track detection algorithm from
    extremeweatherbench.events.tropical_cyclone to identify cyclone centers
    based on SLP minima, closed contours, and wind speed criteria.
    
    Args:
        zarr_path: Path to the filtered ERA5 zarr file.
        output_csv_path: Optional path to save the track as CSV. If None, only returns DataFrame.
        **track_detection_kwargs: Additional keyword arguments passed to
            generate_tc_tracks_by_init_time for customizing track detection.
        
    Returns:
        DataFrame with columns: valid_time, latitude, longitude
    """

    variable_calculator = TropicalCycloneTrackVariables(**track_detection_kwargs)

    print(f"Loading zarr file: {zarr_path}")

    structured_group_list = get_structured_group_list(zarr_path, event_types=event_types)

    lt_ds_list = []

    for entry in structured_group_list:
        event_type, case_id, offset, lead_time = entry
        print(f"\nEvent {case_id}, Type: {event_type}")

        match event_type:
            case "tropical_cyclone":
                era5_ds = xr.open_dataset(zarr_path, engine="zarr", group=f"events_{event_type}_{case_id}_lt{lead_time if lead_time >= 0 else f'm{-lead_time}'}_off{offset}")
                        
                print(f"\nDataset structure:")
                print(f"  Dimensions: {dict(era5_ds.sizes)}")
                print(f"  Variables: {list(era5_ds.data_vars)}")
                print(f"  Coordinates: {list(era5_ds.coords)}")

                # lead_times = era5_ds.lead_time.values
                num_ensembles = 10
                ensemble_members = era5_ds.ensemble.values
                if num_ensembles is not None:
                    ensemble_members = ensemble_members[:num_ensembles]
                    print(f"Limiting processing to first {num_ensembles} ensemble members: {ensemble_members}")
        
                # print(reformatted_ds)
                
                # Extract paths for tropical cyclones
                print("=" * 70)
                print("Extracting IBTrACS Path Data for Tropical Cyclone Events")
                print("=" * 70)
                
                # Get all tropical cyclone event IDs
                #print(f"\nFound {len(case_ids)} tropical cyclone events")
                
                # Extract the path data
                event_start_time = get_case_init_time(case_id)
                ibtracs_results = extract_ibtracs_path_data([case_id])
        
                for event_id, df in ibtracs_results.items():
                    print(f"Attempting to extract track for event {event_id}")
        
                    ds = xr.Dataset.from_dataframe(df)
                    # print(ds)

                    # lt_ds_list = []

                    # for lt in lead_times:
                    lt = lead_time
                    # Prepare data for TC detection
                    print(f"\nPreparing data with lt {lt} for TC track detection...")
                    # reformatted_ds = prepare_era5_data_for_tc_detection(era5_ds.sel(lead_time=[lt]), event_start=event_start_time)
                    reformatted_ds = prepare_era5_data_for_tc_detection(era5_ds, event_start=event_start_time)
                    print("Data preparation complete.\n")

                    member_ds_list = []

                    for member in ensemble_members:
                        member_ds = reformatted_ds.sel(ensemble=member)
                        print(f"Ensemble member {member}")
                        new_track_ds = variable_calculator.get_or_compute_tracks(data=member_ds, _target_dataset=ds)

                        
                        if len(new_track_ds.lead_time.values) < 1:
                            print(f"No viable track found for ensemble member {member}")
                            continue


                        print(new_track_ds)
                        
                        # continue
        
                        track_ds = reformat_track_ds(new_track_ds, member, lt)

                        member_ds_list.append(track_ds)

                    lt_ds_list.append(xr.concat(member_ds_list, dim="ensemble"))

            case _:
                print(f"Unimplemented event type {event_type}")
                continue
    if not lt_ds_list:
        print("\n❌ CRITICAL: lt_ds_list is empty. No tracks were successfully detected or matched.")
        print("💡 Possible reasons:")
        print("   1. The Zarr group path might be empty or missing variables.")
        print("   2. TempestExtremes contour thresholds (--slp-contour) are filtering out all points.")
        print("   3. Time coordinates between ERA5 and IBTrACS do not overlap.")
        return pd.DataFrame()
    final_ds = xr.concat(lt_ds_list, dim="init_index")
    
    print(final_ds)
        
    fname = f"tc_track_event_{event_id}_and_maybe_more.csv"

    filepath = os.path.join(output_csv_path, fname)
    
    # Convert MultiIndex coordinates to regular columns before saving
    final_df = final_ds.to_dataframe().reset_index().dropna()
    # 2. IBTrACS (Actual) data prepare karein
    target_df = ibtracs_results[event_id].reset_index()
    
    # Columns ko rename karein taaki confusion na ho
    target_df = target_df[['valid_time', 'latitude', 'longitude', 'air_pressure_at_mean_sea_level', 'surface_wind_speed']].rename(
        columns={
            'latitude': 'actual_latitude',
            'longitude': 'actual_longitude',
            'air_pressure_at_mean_sea_level': 'actual_pressure',
            'surface_wind_speed': 'actual_wind_speed'
        }
    )

    # 3. Model predicted aur Actual ko valid_time par merge karein
    merged_df = pd.merge(final_df, target_df, on='valid_time', how='inner')

    # 4. Save merged CSV
    merged_df.to_csv(filepath, index=False)
    print(f"Saved merged Predicted vs Actual: {filepath}")
    return merged_df
    

